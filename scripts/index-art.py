"""Inspect alpha bounds and write atlas metadata; never modifies source images."""
import json
import math
from pathlib import Path
from PIL import Image

root = Path(__file__).resolve().parents[1] / 'dist'
names = {'settlements': 'settlements-v5.png', 'nature': 'nature-v5.png', 'people': 'people-v5.png', 'transport': 'transport-v5.png'}
bands = {'settlements': [0, 362, 710, 1086], 'nature': [0, 470, 730, 1086], 'people': [0, 308, 600, 890, 1254]}
nature_bounds = {4: [470, 710], 5: [470, 725], 6: [470, 734], 7: [470, 720], 8: [710, 1086], 9: [725, 1086], 10: [734, 1086], 11: [735, 1086]}
frames = {}
rnd = lambda x: math.floor(x + .5)
for name, filename in names.items():
    image = Image.open(root / 'assets' / 'art' / filename)
    rows = bands.get(name, [0, image.height / 2, image.height])
    factor = image.height / rows[-1]
    count = 4 if name == 'people' else (12 if name in ['nature', 'settlements'] else 8)
    for index in range(count):
        for frame in range(4 if name == 'people' else 1):
            row, column = (index, frame) if name == 'people' else divmod(index, 4)
            start, end = nature_bounds.get(index, rows[row:row + 2]) if name == 'nature' else rows[row:row + 2]
            x, y, width, height = rnd(column * image.width / 4), rnd(start * factor), rnd(image.width / 4), rnd((end - start) * factor)
            cell = image.crop((x, y, x + width, y + height))
            mask = cell.getchannel('A').point(lambda a: 255 if a > 24 else 0)
            bounds = mask.getbbox()
            if not bounds:
                raise ValueError(f'Empty sprite: {name}:{index}:{frame}')
            left, top, right, bottom = bounds
            frames[f'{name}:{index}:{frame}'] = dict(rect=[x + left, y + top, right - left, bottom - top], offsetX=left - width / 2, offsetY=top - bottom + 1, cellWidth=width, cellHeight=height, bottom=bottom - 1, inkWidth=right - left, inkHeight=bottom - top)
            if name == 'settlements':
                small = mask.crop(bounds).resize((24, 24), Image.Resampling.BOX)
                frames[f'{name}:{index}:{frame}']['hitRows'] = [sum(1 << xx for xx in range(24) if small.getpixel((xx, yy)) > 48) for yy in range(24)]
(root / 'realism-frames.js').write_text('// Generated by scripts/index-art.py from original alpha channels.\nexport const FRAMES=' + json.dumps(frames, separators=(',', ':')) + ';\n', encoding='utf-8')
print(f'Indexed {len(frames)} sprites without changing source PNGs.')
